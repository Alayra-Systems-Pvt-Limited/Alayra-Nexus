-- ── Foreign keys, restated with the ON UPDATE the schema declares ─────────────────────────────
--
-- Dropped and re-added rather than altered, because PostgreSQL has no ALTER CONSTRAINT for a
-- referential action. The ON DELETE action of each is unchanged — it is written out here so a
-- reviewer can see that for themselves rather than trust the sentence above.

ALTER TABLE "NexusKey" DROP CONSTRAINT "NexusKey_providerId_fkey";
ALTER TABLE "NexusKey" ADD  CONSTRAINT "NexusKey_providerId_fkey"
  FOREIGN KEY ("providerId") REFERENCES "NexusProvider"("id") ON DELETE CASCADE ON UPDATE CASCADE;

ALTER TABLE "NexusKey" DROP CONSTRAINT "NexusKey_ownerTeamId_fkey";
ALTER TABLE "NexusKey" ADD  CONSTRAINT "NexusKey_ownerTeamId_fkey"
  FOREIGN KEY ("ownerTeamId") REFERENCES "Team"("id") ON DELETE CASCADE ON UPDATE CASCADE;

ALTER TABLE "NexusTeamKey" DROP CONSTRAINT "NexusTeamKey_teamId_fkey";
ALTER TABLE "NexusTeamKey" ADD  CONSTRAINT "NexusTeamKey_teamId_fkey"
  FOREIGN KEY ("teamId") REFERENCES "Team"("id") ON DELETE SET NULL ON UPDATE CASCADE;

ALTER TABLE "DomainAlias" DROP CONSTRAINT "DomainAlias_teamId_fkey";
ALTER TABLE "DomainAlias" ADD  CONSTRAINT "DomainAlias_teamId_fkey"
  FOREIGN KEY ("teamId") REFERENCES "Team"("id") ON DELETE CASCADE ON UPDATE CASCADE;

-- Last, and deliberately: this is the one that scans a large table.
ALTER TABLE "TokenUsage" DROP CONSTRAINT "TokenUsage_nexusTeamKeyId_fkey";
ALTER TABLE "TokenUsage" ADD  CONSTRAINT "TokenUsage_nexusTeamKeyId_fkey"
  FOREIGN KEY ("nexusTeamKeyId") REFERENCES "NexusTeamKey"("id") ON DELETE SET NULL ON UPDATE CASCADE;
